/// Proportional advance: the glyph's own width plus a gap.
fn advance(c: char) -> f64 {
    let g = glyph(c);
    if g.is_empty() {
        return 4.0;
    }
    let (lo, hi) = g.iter().flat_map(|p| p.iter()).fold((f32::MAX, f32::MIN), |(lo, hi), q| (lo.min(q.0), hi.max(q.0)));
    (hi - lo).max(1.0) as f64 + 1.8
}

fn left(c: char) -> f64 {
    glyph(c).iter().flat_map(|p| p.iter()).map(|q| q.0 as f64).fold(f64::MAX, f64::min).min(4.0)
}

/// Width of text at a cap height of size pixels.
/// The strokes of a character on its grid: polylines of (x, y), x-height 4, ascender 6, descender -2.
pub fn char_strokes(c: char) -> Vec<Vec<(f64, f64)>> {
    glyph(c.to_ascii_lowercase()).iter().map(|p| p.iter().map(|q| (q.0 as f64, q.1 as f64)).collect()).collect()
}

/// How far a character advances, on its grid.
pub fn char_advance(c: char) -> f64 {
    advance(c.to_ascii_lowercase())
}

pub fn width(text: &str, size: f64) -> f64 {
    text.chars().map(|c| advance(c.to_ascii_lowercase())).sum::<f64>() * size / 6.0
}

/// Line segments drawing text with its baseline starting at origin (screen pixels, y down).
pub fn strokes(text: &str, origin: DVec2, size: f64) -> Vec<(DVec2, DVec2)> {
    let k = size / 6.0;
    let mut out = Vec::new();
    let mut x = origin.x;
    for c in text.chars() {
        let c = c.to_ascii_lowercase();
        let x0 = x - left(c) * k;
        x += advance(c) * k;
        for poly in glyph(c) {
            for w in poly.windows(2) {
                let p = |q: (f32, f32)| DVec2::new(x0 + q.0 as f64 * k, origin.y - q.1 as f64 * k);
                out.push((p(w[0]), p(w[1])));
            }
        }
    }
    out
}
